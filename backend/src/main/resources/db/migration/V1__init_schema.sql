-- Kernel schema, from the ER diagram (docs/uml/11-er.png).
-- Money uses decimal, never floating point. Kept portable so it also runs on H2 in tests.

create table users (
    id            bigint generated by default as identity primary key,
    name          varchar(120)  not null,
    email         varchar(255)  not null unique,
    phone         varchar(30),
    password_hash varchar(255)  not null,
    role          varchar(20)   not null default 'INVESTOR',
    kyc_status    varchar(20)   not null default 'PENDING',
    created_at    timestamp     not null default current_timestamp
);

create table wallets (
    id       bigint generated by default as identity primary key,
    user_id  bigint         not null unique references users(id),
    balance  decimal(19, 4) not null default 0,
    currency varchar(3)     not null default 'NGN',
    constraint wallets_balance_non_negative check (balance >= 0)
);

create table risk_profiles (
    id            bigint generated by default as identity primary key,
    user_id       bigint      not null references users(id),
    score         int         not null,
    category      varchar(20) not null,
    horizon_years int         not null,
    taken_at      timestamp   not null default current_timestamp
);

create table goals (
    id            bigint generated by default as identity primary key,
    user_id       bigint         not null references users(id),
    name          varchar(120)   not null,
    target_amount decimal(19, 4) not null,
    target_date   date
);

create table assets (
    id             bigint generated by default as identity primary key,
    symbol         varchar(20)    not null unique,
    name           varchar(160)   not null,
    asset_class    varchar(20)    not null,
    sector         varchar(60),
    exchange       varchar(30),
    currency       varchar(3)     not null default 'NGN',
    last_price     decimal(19, 4) not null,
    dividend_yield decimal(9, 4)  not null default 0,
    risk_rating    int            not null
);

create table portfolios (
    id                  bigint generated by default as identity primary key,
    user_id             bigint        not null references users(id),
    goal_id             bigint        references goals(id),
    name                varchar(120)  not null,
    target_weights      text,                       -- JSON text: {"GTCO":0.2,...}
    rebalance_threshold decimal(9, 4) not null default 0.05
);

create table holdings (
    id           bigint generated by default as identity primary key,
    portfolio_id bigint         not null references portfolios(id),
    asset_id     bigint         not null references assets(id),
    units        decimal(19, 6) not null default 0,
    average_cost decimal(19, 4) not null default 0,
    constraint holdings_unique unique (portfolio_id, asset_id)
);

create table invest_plans (
    id           bigint generated by default as identity primary key,
    portfolio_id bigint         not null references portfolios(id),
    amount       decimal(19, 4) not null,
    frequency    varchar(10)    not null,           -- WEEKLY | MONTHLY
    next_run     timestamp      not null,
    status       varchar(15)    not null default 'ACTIVE',
    failed_runs  int            not null default 0
);

create table recommendations (
    id              bigint generated by default as identity primary key,
    user_id         bigint         not null references users(id),
    risk_profile_id bigint         references risk_profiles(id),
    budget          decimal(19, 4) not null,
    status          varchar(15)    not null default 'PROPOSED',
    created_at      timestamp      not null default current_timestamp
);

create table recommended_items (
    id                bigint generated by default as identity primary key,
    recommendation_id bigint         not null references recommendations(id),
    asset_id          bigint         not null references assets(id),
    weight            double precision not null,
    amount            decimal(19, 4) not null,
    units             decimal(19, 6) not null,
    rationale         text           not null
);

create table transactions (
    id         bigint generated by default as identity primary key,
    wallet_id  bigint         not null references wallets(id),
    asset_id   bigint         references assets(id),
    type       varchar(20)    not null,
    amount     decimal(19, 4) not null,
    units      decimal(19, 6),
    reference  varchar(80)    not null unique,
    status     varchar(15)    not null default 'PENDING',
    created_at timestamp      not null default current_timestamp
);

create table price_alerts (
    id        bigint generated by default as identity primary key,
    user_id   bigint         not null references users(id),
    asset_id  bigint         not null references assets(id),
    threshold decimal(19, 4) not null,
    direction varchar(10)    not null,
    status    varchar(15)    not null default 'ACTIVE'
);

create index idx_invest_plans_due on invest_plans (status, next_run);
create index idx_transactions_wallet on transactions (wallet_id, created_at);
